'use strict';

// Расшифровка видов занятий. Основной источник — легенда из подвала файла
// («Обозначения видов занятий»), она парсится при импорте и хранится в settings.
// Но в легенде код «л» неоднозначен (и «лекция», и «лабораторные»), а часть
// кодов из сетки (ЛР, ГЗ, ЗО) в легенде не перечислена отдельно — для них
// используется этот резервный словарь.
const TYPE_FALLBACK = {
  л: 'лекция',
  лр: 'лабораторная работа',
  лз: 'лабораторное занятие',
  гз: 'групповое занятие',
  гу: 'групповое упражнение',
  пз: 'практическое занятие',
  п: 'практическое занятие',
  с: 'семинар',
  кр: 'контрольная работа',
  зо: 'зачёт с оценкой',
  ср: 'самостоятельная работа',
};

// Нормализация кода: убираем хвостовые точки/пробелы, приводим к нижнему регистру.
function normCode(code) {
  return String(code || '')
    .trim()
    .replace(/[.\s]+$/, '')
    .toLowerCase();
}

/**
 * Полное название вида занятия по коду. Сначала — легенда из подвала
 * (регистронезависимо), затем — резервный словарь, иначе исходный код.
 * @param {string} code код из сетки (Л, ЛР, П…)
 * @param {object} [legend] карта { код: полное название } из подвала
 */
function expandType(code, legend) {
  if (!code) return '';
  const key = normCode(code);
  if (legend) {
    for (const [k, v] of Object.entries(legend)) {
      if (normCode(k) === key) return v;
    }
  }
  return TYPE_FALLBACK[key] || code;
}

// Практический вид занятия — всё, кроме лекции и форм контроля (зачёт, экзамен).
// По этому признаку гостю разрешена правка вида занятия: только практическое и
// только на практическое (см. guestEditLesson в services/scheduleService.js).
function isPracticalType(code) {
  const t = normCode(code);
  return !!t && t !== 'л' && !/^(э|экз|экзамен|зач|зч|зо|з\/о|зачет|зачёт)$/.test(t);
}

// «Тема 1», «Т1», «Т. 1», «Т.1» → «Т.1»; прочее (ВВ, ЗАКЛ…) оставляем как есть.
function topicLabel(topic) {
  if (!topic) return '';
  const m = String(topic).match(/^(?:Тема|Т)\.?\s*(\d+)$/i);
  return m ? `Т.${m[1]}` : String(topic);
}

module.exports = { TYPE_FALLBACK, expandType, isPracticalType, topicLabel };
